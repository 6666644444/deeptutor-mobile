const { withAndroidManifest, withMainApplication, withXcodeProject, IOSConfig } = require("expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");
module.exports = (config) => {
  config = withXcodeProject(config, result => {
    const projectName = result.modRequest.projectName;
    const filename = "DTMWebSocketPolicy.m";
    const filepath = path.join(result.modRequest.platformProjectRoot, projectName, filename);
    fs.writeFileSync(filepath, `// Generated by with-network.cjs. Apache-2.0.
#import <React/RCTWebSocketModule.h>
#import <SocketRocket/SRWebSocket.h>
__attribute__((constructor)) static void DTMInstallWebSocketPolicy(void) {
  RCTSetCustomSRWebSocketProvider(^SRWebSocket *(NSURLRequest *request) {
    NSMutableURLRequest *isolated = [request mutableCopy];
    [isolated setValue:nil forHTTPHeaderField:@"Cookie"];
    isolated.HTTPShouldHandleCookies = NO;
    return [[SRWebSocket alloc] initWithURLRequest:isolated];
  });
}
`);
    IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath: `${projectName}/${filename}`, groupName: projectName, project: result.modResults });
    return result;
  });
  config = withMainApplication(config, result => {
    const marker = "// DeepTutor isolated WebSocket transport";
    if (!result.modResults.contents.includes(marker)) {
      result.modResults.contents = result.modResults.contents.replace("super.onCreate()", `super.onCreate()
    ${marker}
    com.facebook.react.modules.websocket.WebSocketModule.setCustomClientBuilder { builder ->
      builder.followRedirects(false).followSslRedirects(false)
        .cookieJar(okhttp3.CookieJar.NO_COOKIES)
        .addInterceptor { chain ->
          chain.proceed(chain.request().newBuilder().removeHeader("Cookie").build())
        }
    }`);
    }
    return result;
  });
  return withAndroidManifest(config, (result) => {
  // Dynamic LAN hosts cannot be enumerated at build time. The client rejects
  // cleartext origins outside private LAN ranges before creating any request.
  result.modResults.manifest.application[0].$["android:usesCleartextTraffic"] = "true";
  result.modResults.manifest.application[0].$["android:allowBackup"] = "false";
  return result;
  });
};
